"""Generate docs/GRAPH.md and docs/CONTROLS.md from the graph dump written by street/build.py.

    python3 scripts/graph_doc.py my_effect.graph.json --top "My Effect" --out docs/

GRAPH.md: the group hierarchy (which group instances which), each group's description, frames (the readable
"blocks" inside it), node counts and interface. CONTROLS.md: the Storybook Street modifier panel by panel, with
defaults, ranges and descriptions. Both are regenerated, never edited by hand, so they cannot drift from the
built graph.
"""
import collections, json, pathlib, sys

import argparse
ap = argparse.ArgumentParser()
ap.add_argument("graph", help="graph dump written by nodekit.inspect.dump_groups")
ap.add_argument("--top", required=True, help="name of the top-level (modifier) node group")
ap.add_argument("--out", default="docs", help="directory for GRAPH.md and CONTROLS.md")
a = ap.parse_args()
OUTDIR = pathlib.Path(a.out)
OUTDIR.mkdir(parents=True, exist_ok=True)
groups = {g["name"]: g for g in json.loads(pathlib.Path(a.graph).read_text())}
TOP = a.top


def fmt(v):
    if isinstance(v, float):
        return f"{v:g}"
    if isinstance(v, list):
        if len(v) == 4 and all(isinstance(x, (int, float)) for x in v):
            r, g, b = (max(0, min(1, x)) for x in v[:3])
            # linear -> sRGB hex for readability
            to = lambda c: round(255 * (12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055))
            return f"`#{to(r):02X}{to(g):02X}{to(b):02X}`"
        return "(" + ", ".join(fmt(x) for x in v) + ")"
    return "" if v is None else str(v)


def children(g):
    return [n["props"].get("node_tree") for n in g["nodes"] if n["props"].get("node_tree")]


# ---- GRAPH.md ---------------------------------------------------------------------------------------------
lines = ["# Graph", "", "Generated by `scripts/graph_doc.py` from the built file; do not edit by hand.", "",
         "## Hierarchy", "", "Each line is a node group; indented lines are the groups it instances "
         "(×n = instanced n times inside its parent).", "", "```text"]
seen = set()


def tree(name, depth=0, count=1):
    g = groups.get(name)
    if g is None:
        return
    n_nodes = len([n for n in g["nodes"] if n["type"] not in ("NodeGroupInput", "NodeGroupOutput")])
    mult = f" ×{count}" if count > 1 else ""
    again = " (see above)" if name in seen else ""
    lines.append(f"{'  ' * depth}{name}{mult}  [{n_nodes} nodes, {len(g['frames'])} frames]{again}")
    if name in seen:
        return
    seen.add(name)
    for child, c in collections.Counter(children(g)).items():
        tree(child, depth + 1, c)


tree(TOP)
lines += ["```", ""]
total_nodes = sum(len(g["nodes"]) for g in groups.values() if g["type"] == "GeometryNodeTree")
lines += [f"{len([g for g in groups.values() if g['type'] == 'GeometryNodeTree'])} Geometry Nodes groups "
          f"({total_nodes} nodes), {len([g for g in groups.values() if g['type'] == 'ShaderNodeTree'])} shader "
          "groups.", "", "## Groups", ""]
order = [n for n in seen] + sorted(set(groups) - seen)
for name in sorted(order, key=lambda n: (n != TOP, n)):
    g = groups[name]
    lines += [f"### {name}", "", g["description"] or "_(no description)_", ""]
    if g["frames"]:
        lines += ["Blocks: " + "; ".join(g["frames"]), ""]
    ins = [i for i in g["interface"] if i.get("io") == "INPUT"]
    outs = [i for i in g["interface"] if i.get("io") == "OUTPUT"]
    if name != TOP and ins:
        lines += ["Inputs: " + ", ".join(f"{i['name']}" for i in ins), ""]
    if outs:
        lines += ["Outputs: " + ", ".join(f"{i['name']}" for i in outs), ""]
(OUTDIR / "GRAPH.md").write_text("\n".join(lines) + "\n")

# ---- CONTROLS.md ------------------------------------------------------------------------------------------
top = groups[TOP]
lines = ["# Controls", "", f"The `{TOP}` modifier panel, generated by `scripts/graph_doc.py` from the built "
         "file. Defaults are the reference look. Colours are shown as sRGB.", ""]
panels = collections.OrderedDict()
for it in top["interface"]:
    if it.get("io") != "INPUT" or it["type"] == "NodeSocketGeometry":
        continue
    panels.setdefault(it.get("panel") or "Main", []).append(it)
for panel, items in panels.items():
    lines += [f"## {panel}", "", "| Control | Default | Range | What it does |", "|---|---|---|---|"]
    for it in items:
        rng = ""
        if "min_value" in it and isinstance(it["min_value"], (int, float)) and abs(it["min_value"]) < 1e8:
            rng = f"{fmt(it['min_value'])} – {fmt(it['max_value'])}"
        lines.append(f"| {it['name']} | {fmt(it.get('default_value'))} | {rng} | {it['description']} |")
    lines.append("")
(OUTDIR / "CONTROLS.md").write_text("\n".join(lines) + "\n")
print(f"wrote {OUTDIR}/GRAPH.md and {OUTDIR}/CONTROLS.md:", len(panels), "panels,", len(seen), "groups in hierarchy")
