#!/usr/bin/env python3
"""procedural-blender-nodes command line. Plain Python 3; commands that need Blender start it themselves.

    python3 scripts/nodes_tools.py search curve fence        rank library groups by name, summary, tags, uses
    python3 scripts/nodes_tools.py index [--check]           regenerate references/library-index.md
    python3 scripts/nodes_tools.py check                     static rules, then build every group in Blender:
                                                             lint, node warnings, evaluation on test inputs
    python3 scripts/nodes_tools.py test [-k name]            numeric property tests (tests/ in the repository)
    python3 scripts/nodes_tools.py try  -- <try_group args>  build one group in a test scene (scripts/try_group.py)

Blender is found as $BLENDER, else `blender` on PATH, else the macOS app bundle.
"""
import ast, os, pathlib, re, shutil, subprocess, sys

SKILL = pathlib.Path(__file__).resolve().parents[1]
LIB = SKILL / "library"
REPO = SKILL.parents[1]


def blender_exe():
    for cand in (os.environ.get("BLENDER"), shutil.which("blender"),
                 "/Applications/Blender.app/Contents/MacOS/Blender"):
        if cand and pathlib.Path(cand).exists():
            return cand
    sys.exit("Blender not found: set $BLENDER or put `blender` on PATH (Blender 5.2+)")


def run_blender(script, *args):
    cmd = [blender_exe(), "-b", "--factory-startup", "--python", str(script), "--", *args]
    return subprocess.run(cmd).returncode


# ---- static reading of the library (no Blender) -----------------------------------------------------------
def module_order():
    tree = ast.parse((LIB / "__init__.py").read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and node.targets[0].id == "MODULE_ORDER":
            return [e.value for e in node.value.elts]
    return []


def read_library():
    """[{name, kind, tags, use, summary, module, builder, line, inputs}] from @nodegroup decorators."""
    groups = []
    for mod in module_order():
        path = LIB / f"{mod}.py"
        if not path.exists():
            continue
        tree = ast.parse(path.read_text())
        for fn in [n for n in tree.body if isinstance(n, ast.FunctionDef)]:
            for dec in fn.decorator_list:
                if isinstance(dec, ast.Call) and getattr(dec.func, "id", "") == "nodegroup":
                    meta = {"name": ast.literal_eval(dec.args[0]), "kind": "GEOMETRY", "tags": [], "use": "",
                            "module": mod, "builder": fn.name, "line": fn.lineno}
                    for kw in dec.keywords:
                        meta[kw.arg] = ast.literal_eval(kw.value)
                    doc = ast.get_docstring(fn) or ""
                    meta["summary"] = doc.strip().splitlines()[0] if doc.strip() else ""
                    meta["doc"] = doc
                    meta["inputs"] = re.findall(r'\.input\(\s*"([^"]+)"', ast.get_source_segment(path.read_text(), fn))
                    groups.append(meta)
    return groups


def cmd_search(words):
    words = [w.lower() for w in words]
    scored = []
    for g in read_library():
        hay = {"name": g["name"].lower(), "summary": g["summary"].lower(),
               "tags": " ".join(g["tags"]).lower(), "use": g["use"].lower()}
        score = sum(3 * (w in hay["name"]) + 2 * (w in hay["tags"]) + (w in hay["summary"]) + (w in hay["use"])
                    for w in words)
        if score:
            scored.append((score, g))
    for score, g in sorted(scored, key=lambda x: -x[0])[:15]:
        print(f"{g['name']:<28} {g['kind']:<10} library/{g['module']}.py:{g['line']}  {g['summary']}")
        print(f"{'':28} use: {g['use']}")
    if not scored:
        print("no match; try broader words, or read references/library-index.md")


def render_index():
    groups = read_library()
    out = ["# Library index", "",
           "Generated by `python3 scripts/nodes_tools.py index`; do not edit by hand. Build a group with its",
           "builder (`from library.<module> import <builder>; tree = <builder>()`) and instance it with",
           "`Graph.group(tree, ...)`.", ""]
    for mod in module_order():
        gs = [g for g in groups if g["module"] == mod]
        if not gs:
            continue
        out += [f"## {mod}", "", "| Group | Kind | Builder | Inputs | Summary | Use for |", "|---|---|---|---|---|---|"]
        for g in gs:
            out.append(f"| `{g['name']}` | {g['kind'].lower()} | `{g['builder']}()` | "
                       f"{', '.join(g['inputs'][:10])}{' …' if len(g['inputs']) > 10 else ''} | {g['summary']} | "
                       f"{g['use']} |")
        out.append("")
    out.append(f"{len(groups)} groups in {len([m for m in module_order() if (LIB / f'{m}.py').exists()])} modules.")
    return "\n".join(out) + "\n"


def cmd_index(check=False):
    path = SKILL / "references" / "library-index.md"
    text = render_index()
    if check:
        if not path.exists() or path.read_text() != text:
            sys.exit("references/library-index.md is stale: run `python3 scripts/nodes_tools.py index`")
        print("library-index.md is up to date")
        return
    path.write_text(text)
    print("wrote", path.relative_to(SKILL))


def static_check():
    problems = []
    order = module_order()
    names = {}
    for g in read_library():
        where = f"library/{g['module']}.py:{g['line']}"
        if not g["name"].startswith("NK "):
            problems.append(f"{where}: group name {g['name']!r} must start with 'NK '")
        if g["name"] in names:
            problems.append(f"{where}: duplicate group name {g['name']!r} (also {names[g['name']]})")
        names[g["name"]] = where
        if not g["summary"]:
            problems.append(f"{where}: {g['builder']}() needs a one-line docstring summary")
        if not g["use"]:
            problems.append(f"{where}: {g['name']} needs use=... naming concrete subjects")
    for i, mod in enumerate(order):
        path = LIB / f"{mod}.py"
        if not path.exists():
            continue
        for imp in re.findall(r"^\s*(?:from\s+library\.(\w+)|from\s+library\s+import\s+(\w+))", path.read_text(), re.M):
            dep = imp[0] or imp[1]
            if dep in order and order.index(dep) >= i:
                problems.append(f"library/{mod}.py imports library.{dep}, which is not earlier in MODULE_ORDER")
    return problems


def cmd_check():
    problems = static_check()
    for p in problems:
        print("ERROR", p)
    print(f"static: {len(problems)} problem(s)")
    rc = run_blender(SKILL / "scripts" / "_check_in_blender.py")
    sys.exit(1 if problems or rc else 0)


def main():
    if len(sys.argv) < 2 or sys.argv[1] in ("-h", "--help"):
        print(__doc__)
        return
    cmd, rest = sys.argv[1], sys.argv[2:]
    if cmd == "search":
        cmd_search(rest)
    elif cmd == "index":
        cmd_index("--check" in rest)
    elif cmd == "check":
        cmd_check()
    elif cmd == "test":
        sys.exit(run_blender(REPO / "tests" / "run_tests.py", *rest))
    elif cmd == "try":
        sys.exit(run_blender(SKILL / "scripts" / "try_group.py", *[r for r in rest if r != "--"]))
    else:
        sys.exit(f"unknown command {cmd!r}; see --help")


if __name__ == "__main__":
    main()
